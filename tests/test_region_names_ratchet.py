"""Ratchet on region-specific names in engine code (PLAT-3 slice 1, PLATFORM_ARCHITECTURE.md §4).

Counts matches of the region-name terms per ``src/atlas/**/*.py`` file and compares them with
``tests/fixtures/region_names_baseline.json``. A file may not gain matches, and a new file may
not contain any. Lowering a count is allowed and prints a hint to lower the baseline.

Regenerate the baseline after removing names (never to add them):

    py -3.14 tests/test_region_names_ratchet.py --write-baseline
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ENGINE_ROOT = REPO_ROOT / "src" / "atlas"
EXCLUDED_DIR = ENGINE_ROOT / "regions"
BASELINE_PATH = REPO_ROOT / "tests" / "fixtures" / "region_names_baseline.json"
TERMS = ("California", "Californian", "RWQCB", "CEDEN", "DTSC", "OPC", "Sea Grant")
TERM_RE = re.compile(
    r"\b(?:California|Californian|RWQCB|CEDEN|DTSC|OPC|Sea\s+Grant)\b", re.IGNORECASE
)


def count_region_names() -> dict[str, int]:
    """Return ``{repo-relative posix path: match count}`` for files with at least one match."""
    counts: dict[str, int] = {}
    for path in sorted(ENGINE_ROOT.rglob("*.py")):
        if EXCLUDED_DIR in path.parents:
            continue
        matches = len(TERM_RE.findall(path.read_text(encoding="utf-8", errors="replace")))
        if matches:
            counts[path.relative_to(REPO_ROOT).as_posix()] = matches
    return counts


def load_baseline() -> dict[str, int]:
    return dict(json.loads(BASELINE_PATH.read_text(encoding="utf-8"))["files"])


def test_region_name_counts_do_not_rise() -> None:
    baseline = load_baseline()
    current = count_region_names()

    new_files = sorted(path for path in current if path not in baseline)
    rose = sorted(
        f"{path}: {baseline[path]} -> {current[path]}"
        for path in current
        if path in baseline and current[path] > baseline[path]
    )
    problems = [f"new file with region names: {path} ({current[path]})" for path in new_files]
    problems += [f"region-name count rose: {entry}" for entry in rose]
    assert not problems, (
        "Region names in engine code must not grow. Move the California-specific code behind "
        "region config or regions/california/ adapters.\n" + "\n".join(problems)
    )

    lowered = sorted(path for path in baseline if current.get(path, 0) < baseline[path])
    if lowered:
        print(
            "Region-name counts fell; lower the baseline with "
            "`py -3.14 tests/test_region_names_ratchet.py --write-baseline`: " + ", ".join(lowered)
        )


def main(argv: list[str]) -> int:
    if argv != ["--write-baseline"]:
        print("usage: py -3.14 tests/test_region_names_ratchet.py --write-baseline")
        return 2
    counts = count_region_names()
    payload = {
        "terms": list(TERMS),
        "note": "Generated by test_region_names_ratchet.py --write-baseline. Counts may only fall.",
        "files": counts,
    }
    BASELINE_PATH.write_text(
        json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8"
    )
    print(f"wrote {len(counts)} files, {sum(counts.values())} matches to {BASELINE_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
