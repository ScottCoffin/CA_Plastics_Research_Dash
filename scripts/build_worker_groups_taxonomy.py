"""Generate worker/src/groups_taxonomy.ts from config/groups_taxonomy.yml (Add-on A4, CG-6a).

  py -3.14 scripts/build_worker_groups_taxonomy.py          # write the module (LF)
  py -3.14 scripts/build_worker_groups_taxonomy.py --check  # exit 1 when stale

Every top-level list in the YAML becomes a readonly string array in the YAML order (the order drives
later views, so it is never sorted). The schema name becomes GROUPS_SCHEMA.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config" / "groups_taxonomy.yml"
TARGET = ROOT / "worker" / "src" / "groups_taxonomy.ts"

HEADER = (
    "// Generated by scripts/build_worker_groups_taxonomy.py from config/groups_taxonomy.yml.\n"
    "// Do not edit by hand. Regenerate after changing the YAML:\n"
    "// py -3.14 scripts/build_worker_groups_taxonomy.py\n"
)


def render(source: Path = SOURCE) -> str:
    data = yaml.safe_load(source.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise SystemExit(f"{source}: top level must be a mapping")
    lines = [HEADER, f"export const GROUPS_SCHEMA = {json.dumps(str(data['schema']))};", ""]
    for key, value in data.items():
        if key == "schema":
            continue
        if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
            raise SystemExit(f"{source}: {key} must be a list of strings")
        if len(set(value)) != len(value):
            raise SystemExit(f"{source}: {key} has duplicate values")
        lines.append(f"export const {key.upper()}: readonly string[] = [")
        lines.extend(f"  {json.dumps(item)}," for item in value)
        lines.append("];")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail when the committed module is stale"
    )
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_bytes().decode("utf-8") if TARGET.exists() else None
        if current != text:
            rel = TARGET.relative_to(ROOT).as_posix()
            print(f"stale: {rel} (run without --check)", file=sys.stderr)
            return 1
        print("ok: groups_taxonomy.ts matches config/groups_taxonomy.yml")
        return 0
    with TARGET.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {TARGET.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
