"""Build work-to-grant evidence links (S9.1).

Writes ``data/processed/work_grant_links.parquet`` (ids and evidence only),
``docs/work_grant_links_qc.md`` (aggregates), and the ignored review file
``data/interim/links/work_grant_links_uncertain.csv``.

Network use is limited to NIH RePORTER project lookups for NIH core project
numbers that are not already cached. ``--max-requests`` caps them (default 60);
``--max-requests 0`` runs from cache only. Only counts are printed.
"""

from __future__ import annotations

import argparse
import collections
import csv
from pathlib import Path
from typing import Any

import pyarrow as pa
import pyarrow.parquet as pq

from atlas.link.work_grants import (
    COAST_ACK_PHRASE,
    COAST_SOURCE,
    Link,
    ReviewCandidate,
    build_grant_index,
    combine_links,
    load_cached_ack_texts,
    match_acknowledgements,
    match_fixed_strings,
    match_openalex_awards,
    normalize_award_id,
    reporter_transport,
    resolve_nih_core_nums,
    work_awards,
)

ROOT = Path(__file__).resolve().parents[1]
WORKS = ROOT / "data/interim/works_raw.parquet"
GRANTS_DIR = ROOT / "data/interim/grants"
MERGED = GRANTS_DIR / "grants_merged.parquet"
DEDUPE = GRANTS_DIR / "grants_dedupe_map.csv"
SOURCE_TABLES = ("nih_reporter", "nsf_awards", "usaspending", "ca_sea_grant", "state_funders")
LOOKUP = ROOT / "data/interim/links/nih_project_lookup.json"
REVIEW = ROOT / "data/interim/links/work_grant_links_uncertain.csv"
FULLTEXT_CACHE = ROOT / "data/raw/fulltext_cache/pdf"
OUTPUT = ROOT / "data/processed/work_grant_links.parquet"
QC = ROOT / "docs/work_grant_links_qc.md"

LINK_SCHEMA = pa.schema(
    [
        ("work_id", pa.string()),
        ("grant_key", pa.string()),
        ("grant_source", pa.string()),
        ("evidence_type", pa.string()),
        ("evidence_value", pa.string()),
        ("confidence", pa.string()),
    ]
)


def representative_map(path: Path) -> dict[str, str]:
    with path.open(encoding="utf-8", newline="") as handle:
        return {row["grant_key"]: row["representative_key"] for row in csv.DictReader(handle)}


def _read(path: Path, columns: list[str]) -> list[dict[str, Any]]:
    return pq.read_table(path, columns=columns).to_pylist()


def _qc_lines(
    works: list[dict[str, Any]],
    awards_by_work: dict[str, list[dict[str, Any]]],
    lookup: dict[str, list[str]],
    links: list[Link],
    review: list[ReviewCandidate],
    grant_source: dict[str, str],
    requests: int,
) -> list[str]:
    award_rows = [a for aw in awards_by_work.values() for a in aw]
    family_counts: collections.Counter[str] = collections.Counter()
    distinct_ids: dict[str, set[str]] = collections.defaultdict(set)
    funder_counts: collections.Counter[str] = collections.Counter()
    for award in award_rows:
        raw = str(award.get("funder_award_id") or "").strip()
        aid = normalize_award_id(raw)
        family = aid.family or "other"
        family_counts[family] += 1
        distinct_ids[family].add(raw)
        funder_counts[f"{family}: {award.get('funder_display_name') or 'unknown'}"] += 1
    nih_cores = {
        normalize_award_id(str(a.get("funder_award_id") or "")).key
        for a in award_rows
        if normalize_award_id(str(a.get("funder_award_id") or "")).family == "nih"
    }
    resolved = {c for c in nih_cores if lookup.get(c)}
    linked_works = {link.work_id for link in links}
    by_type = collections.Counter(link.evidence_type for link in links)
    by_source = collections.Counter(link.grant_source for link in links)
    works_with_awards = sum(1 for aw in awards_by_work.values() if aw)
    lines = [
        "# Work-grant links QC (S9.1)",
        "",
        "Generated by `scripts/build_work_grant_links.py`. Aggregates only; no abstracts.",
        "",
        "## Coverage",
        "",
        f"- Works in `works_raw.parquet`: {len(works)}",
        f"- Works with OpenAlex `awards`: {works_with_awards}",
        f"- OpenAlex award entries: {len(award_rows)}",
        f"- Works with at least one link: {len(linked_works)}",
        "",
        "## Award IDs by funder family",
        "",
        "| Family | Entries | Distinct raw IDs |",
        "|---|---:|---:|",
    ]
    for family in ("nih", "nsf", "other"):
        lines.append(
            f"| {family} | {family_counts.get(family, 0)} "
            f"| {len(distinct_ids.get(family, set()))} |"
        )
    lines += [
        "",
        f"- Distinct NIH core project numbers: {len(nih_cores)}",
        f"- NIH core numbers with a RePORTER appl_id: {len(resolved)}",
        "- NIH core numbers without a RePORTER record (or not looked up): "
        f"{len(nih_cores) - len(resolved)}",
        f"- RePORTER requests made in this run: {requests}",
        "",
        "## Top funder names by family",
        "",
    ]
    for name, count in funder_counts.most_common(15):
        lines.append(f"- {name}: {count}")
    lines += [
        "",
        "## Links",
        "",
        f"- Links (one per work and grant): {len(links)}",
        f"- Uncertain candidates kept out of output: {len(review)}",
        "",
        "| Evidence type | Links |",
        "|---|---:|",
    ]
    for evidence in ("openalex-award", "acknowledgement-match", "fixed-string"):
        lines.append(f"| {evidence} | {by_type.get(evidence, 0)} |")
    lines += ["", "| Grant source | Links |", "|---|---:|"]
    for source in sorted(set(grant_source.values()) | set(by_source)):
        lines.append(f"| {source or 'unknown'} | {by_source.get(source, 0)} |")
    lines += [
        "",
        "## Matcher inputs not available",
        "",
        "- Acknowledgement and funding text: cached full-text outputs hold no such "
        f"sections (works with cached text: {len(load_cached_ack_texts(FULLTEXT_CACHE))}). "
        "The acknowledgement matcher is implemented and unit-tested but yields no links.",
        "- COAST fixed string: "
        + (
            f"configured ({COAST_ACK_PHRASE!r})"
            if COAST_ACK_PHRASE
            else "not configured (no exact phrase in repo); no COAST grant rows exist."
        ),
        "- NSF awards from USAspending: the award id is not stored in the table, so only "
        "`nsf_awards` rows are matched by NSF id.",
        "",
    ]
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--max-requests", type=int, default=60)
    args = parser.parse_args(argv)

    works = _read(WORKS, ["openalex_id", "raw_json"])
    awards_by_work = {w["openalex_id"]: work_awards(w["raw_json"]) for w in works}

    merged = _read(MERGED, ["grant_key", "source"])
    grant_source = {r["grant_key"]: r["source"] for r in merged}
    rep = representative_map(DEDUPE)

    rows: list[dict[str, Any]] = []
    for table in SOURCE_TABLES:
        for row in _read(
            GRANTS_DIR / f"{table}.parquet", ["grant_key", "source", "source_award_id"]
        ):
            key = rep.get(row["grant_key"], row["grant_key"])
            if key in grant_source:
                rows.append({**row, "grant_key": key})
    index = build_grant_index(rows)
    targets = sorted(k for k, s in grant_source.items() if s == COAST_SOURCE)

    core_nums = {
        normalize_award_id(str(a.get("funder_award_id") or "")).key
        for aw in awards_by_work.values()
        for a in aw
        if normalize_award_id(str(a.get("funder_award_id") or "")).family == "nih"
    }
    requests = 0

    def counting_transport(body: Any) -> tuple[int, str]:
        nonlocal requests
        requests += 1
        return reporter_transport(body)

    lookup = resolve_nih_core_nums(
        {c for c in core_nums if c},
        cache_path=LOOKUP,
        transport=counting_transport,
        max_requests=args.max_requests,
    )

    ack = load_cached_ack_texts(FULLTEXT_CACHE)
    candidates: list[Link] = []
    review: list[ReviewCandidate] = []
    for work_id, awards in awards_by_work.items():
        links, uncertain = match_openalex_awards(work_id, awards, index, lookup, grant_source)
        candidates.extend(links)
        review.extend(uncertain)
        texts = ack.get(work_id, [])
        candidates.extend(match_acknowledgements(work_id, texts, index, lookup, grant_source))
        candidates.extend(
            match_fixed_strings(work_id, texts, COAST_ACK_PHRASE, targets, grant_source)
        )
    links = combine_links(candidates)
    linked = {(link.work_id, link.grant_key) for link in links}
    review = sorted(
        {r for r in review if (r.work_id, r.grant_key) not in linked},
        key=lambda r: (r.work_id, r.grant_key, r.evidence_value),
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    table = pa.Table.from_pylist(
        [
            {
                "work_id": link.work_id,
                "grant_key": link.grant_key,
                "grant_source": link.grant_source,
                "evidence_type": link.evidence_type,
                "evidence_value": link.evidence_value,
                "confidence": link.confidence,
            }
            for link in links
        ],
        schema=LINK_SCHEMA,
    )
    pq.write_table(table, OUTPUT)

    REVIEW.parent.mkdir(parents=True, exist_ok=True)
    with REVIEW.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["work_id", "grant_key", "evidence_type", "evidence_value", "reason"])
        for r in review:
            writer.writerow([r.work_id, r.grant_key, r.evidence_type, r.evidence_value, r.reason])

    QC.write_text(
        "\n".join(_qc_lines(works, awards_by_work, lookup, links, review, grant_source, requests)),
        encoding="utf-8",
    )
    print(
        f"works={len(works)} links={len(links)} uncertain={len(review)} "
        f"nih_core={len(core_nums)} requests={requests}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
