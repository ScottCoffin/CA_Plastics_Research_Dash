"""Build work-to-dataset evidence links (S9.2).

Writes ``data/processed/work_dataset_links.parquet`` (ids and evidence only),
``docs/work_dataset_links_qc.md`` (aggregates), the ignored review file
``data/interim/links/work_dataset_links_uncertain.csv`` and the ignored DataCite
response cache ``data/interim/links/datacite_work_relations_cache.json``.

Network use is limited to DataCite metadata searches on ``api.datacite.org``.
Batches already in the cache are not re-requested. ``--max-requests`` caps live
requests (default 60); ``--max-requests 0`` runs from cache only. Only counts are
printed.
"""

from __future__ import annotations

import argparse
import collections
from pathlib import Path
from typing import Any

import pyarrow as pa
import pyarrow.parquet as pq

from atlas.link.work_datasets import (
    EVIDENCE_TYPES,
    ReviewRow,
    WorkDatasetLink,
    combine_links,
    das_matches,
    datacite_transport,
    dataset_dois,
    fetch_relation_records,
    load_cached_jats,
    relation_matches,
    work_index,
    write_review_csv,
)

ROOT = Path(__file__).resolve().parents[1]
WORKS = ROOT / "data/interim/works_raw.parquet"
FULLTEXT_CACHE = ROOT / "data/raw/fulltext_cache"
CACHE = ROOT / "data/interim/links/datacite_work_relations_cache.json"
REVIEW = ROOT / "data/interim/links/work_dataset_links_uncertain.csv"
OUTPUT = ROOT / "data/processed/work_dataset_links.parquet"
QC = ROOT / "docs/work_dataset_links_qc.md"

LINK_SCHEMA = pa.schema(
    [
        ("work_id", pa.string()),
        ("dataset_doi", pa.string()),
        ("relation_type", pa.string()),
        ("evidence_type", pa.string()),
        ("evidence_value", pa.string()),
        ("confidence", pa.string()),
    ]
)


def _qc_lines(
    *,
    works: int,
    index: dict[str, dict[str, Any]],
    queried: int,
    fetch: Any,
    records: list[dict[str, Any]],
    jats_pmcids: int,
    links: list[WorkDatasetLink],
    review: list[ReviewRow],
) -> list[str]:
    by_type = collections.Counter(link.evidence_type for link in links)
    by_relation = collections.Counter(link.relation_type for link in links)
    reasons = collections.Counter(row.reason for row in review)
    linked_works = {link.work_id for link in links}
    dataset_records = len(dataset_dois(records))
    lines = [
        "# Work-dataset links QC (S9.2)",
        "",
        "Generated by `scripts/build_work_dataset_links.py`. Aggregates only; no abstracts.",
        "",
        "## Coverage",
        "",
        f"- Works in `works_raw.parquet`: {works}",
        f"- Works with a canonical DOI: {len(index)}",
        f"- DOIs queried against DataCite relations: {queried}",
        f"- DataCite records returned: {len(records)} (dataset-type resources: {dataset_records})",
        f"- Works with JATS XML in the local cache: {jats_pmcids} PMCIDs with cached XML",
        "",
        "## DataCite requests",
        "",
        f"- Requests made in this run: {fetch.requests}",
        f"- Batches served from cache: {fetch.cached_batches}",
        f"- Failed batches (not cached, not linked): {fetch.failed_batches}",
        f"- Batches not fetched within the request budget: {fetch.incomplete_batches}",
        "",
        "## Links",
        "",
        f"- Links (one per work and dataset): {len(links)}",
        f"- Works with at least one link: {len(linked_works)}",
        f"- Uncertain candidates kept out of output: {len(review)}",
        "",
        "| Evidence type | Links |",
        "|---|---:|",
    ]
    for evidence in EVIDENCE_TYPES:
        lines.append(f"| {evidence} | {by_type.get(evidence, 0)} |")
    lines += ["", "| DataCite relation type | Links |", "|---|---:|"]
    for relation, count in sorted(by_relation.items()):
        lines.append(f"| {relation} | {count} |")
    lines += ["", "## Uncertain candidates by reason", ""]
    for reason, count in reasons.most_common():
        lines.append(f"- {reason}: {count}")
    lines += [
        "",
        "## Limits",
        "",
        "- DataCite relations are metadata, not proof of use. Only typed paper relations on "
        "dataset-type resources are linked; geographic and topical relevance are not checked.",
        "- DAS-match can only fire for a dataset DOI that is also returned by the DataCite "
        "relation query. No JATS XML is cached yet, so it currently yields no links.",
        "- The committed output is a candidate set for owner review, not published data.",
        "",
    ]
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--max-requests", type=int, default=60)
    args = parser.parse_args(argv)

    raw = pq.read_table(WORKS, columns=["openalex_id", "raw_json"]).to_pylist()
    index = work_index(raw)
    dois = sorted(index)

    fetch = fetch_relation_records(
        dois,
        cache_path=CACHE,
        transport=datacite_transport,
        max_requests=args.max_requests,
    )
    records = fetch.records
    links, review = relation_matches(records, index)

    known = dataset_dois(records)
    pmcids = {w["pmcid"] for w in index.values() if w.get("pmcid")}
    xml = load_cached_jats(FULLTEXT_CACHE, pmcids)
    for doi, work in sorted(index.items()):
        docs = xml.get(work.get("pmcid", ""), [])
        if docs:
            das_links, das_review = das_matches(work["work_id"], doi, docs, known)
            links.extend(das_links)
            review.extend(das_review)

    links = combine_links(links)
    linked = {(link.work_id, link.dataset_doi) for link in links}
    review = sorted(
        {r for r in review if (r.work_id, r.dataset_doi) not in linked},
        key=lambda r: (r.work_id, r.dataset_doi, r.evidence_type, r.evidence_value),
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    table = pa.Table.from_pylist(
        [
            {
                "work_id": link.work_id,
                "dataset_doi": link.dataset_doi,
                "relation_type": link.relation_type,
                "evidence_type": link.evidence_type,
                "evidence_value": link.evidence_value,
                "confidence": link.confidence,
            }
            for link in links
        ],
        schema=LINK_SCHEMA,
    )
    pq.write_table(table, OUTPUT)
    write_review_csv(REVIEW, review)
    QC.write_text(
        "\n".join(
            _qc_lines(
                works=len(raw),
                index=index,
                queried=len(dois),
                fetch=fetch,
                records=records,
                jats_pmcids=len(xml),
                links=links,
                review=review,
            )
        ),
        encoding="utf-8",
    )
    print(
        f"works={len(raw)} dois={len(dois)} records={len(records)} links={len(links)} "
        f"uncertain={len(review)} requests={fetch.requests} "
        f"failed={fetch.failed_batches} incomplete={fetch.incomplete_batches}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
